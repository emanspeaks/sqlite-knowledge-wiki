/* masm2gas: rewrite one of PHP's x86_64_ms_pe_masm.asm files (Zend/asm) into
 * the syntax clang's assembler takes.
 *
 *   masm2gas IN.asm OUT.S
 *
 * PHP ships its fiber context-switch routines for Windows only in Microsoft
 * assembler syntax, and Zig has no Microsoft assembler. The instructions are
 * kept exactly as they are (clang reads Intel syntax); only the directives
 * around them are translated. This is not a general translator: it knows the
 * few directives those files use and refuses anything else.
 */
#include <ctype.h>
#include <stdarg.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static void die(const char *fmt, ...)
{
	va_list ap;
	va_start(ap, fmt);
	fputs("masm2gas: ", stderr);
	vfprintf(stderr, fmt, ap);
	fputc('\n', stderr);
	va_end(ap);
	exit(1);
}

static char *trim(char *s)
{
	while (isspace((unsigned char)*s)) s++;
	char *e = s + strlen(s);
	while (e > s && isspace((unsigned char)e[-1])) *--e = 0;
	return s;
}

static int is_register(const char *s)
{
	static const char *const regs[] = { "rax", "rbx", "rcx", "rdx", "rsi", "rdi", "rbp", "rsp",
		"r8", "r9", "r10", "r11", "r12", "r13", "r14", "r15", NULL };
	for (int i = 0; regs[i]; i++) if (strcmp(s, regs[i]) == 0) return 1;
	return 0;
}

static int is_identifier(const char *s)
{
	if (!(isalpha((unsigned char)*s) || *s == '_')) return 0;
	for (; *s; s++) if (!(isalnum((unsigned char)*s) || *s == '_')) return 0;
	return 1;
}

/* Write an instruction, turning Microsoft hexadecimal numbers (0118h) into
 * the form clang reads (0x0118). */
static void put_instruction(FILE *out, const char *s)
{
	fputs("    ", out);
	while (*s) {
		int starts_token = !(isalnum((unsigned char)s[-1]) || s[-1] == '_');
		if (starts_token && isdigit((unsigned char)*s)) {
			const char *e = s;
			while (isxdigit((unsigned char)*e)) e++;
			if (*e == 'h' && !(isalnum((unsigned char)e[1]) || e[1] == '_')) {
				fprintf(out, "0x%.*s", (int)(e - s), s);
				s = e + 1;
				continue;
			}
		}
		fputc(*s++, out);
	}
	fputc('\n', out);
}

int main(int argc, char **argv)
{
	if (argc != 3) die("usage: masm2gas IN.asm OUT.S");
	FILE *in = fopen(argv[1], "r");
	if (!in) die("cannot open %s", argv[1]);
	FILE *out = fopen(argv[2], "w");
	if (!out) die("cannot write %s", argv[2]);

	fprintf(out, "/* Generated by masm2gas from %s. Do not edit. */\n.intel_syntax noprefix\n",
		strrchr(argv[1], '/') ? strrchr(argv[1], '/') + 1 : argv[1]);

	char line[1024], word[4][256];
	int depth = 0, ended = 0, lineno = 0;
	while (fgets(line, sizeof line, in)) {
		lineno++;
		char *c = strchr(line, ';');
		if (c) *c = 0;
		char *s = trim(line);
		if (!*s) continue;
		if (ended) die("%s:%d: text after END", argv[1], lineno);

		int n = sscanf(s, "%255s %255s %255s %255s", word[0], word[1], word[2], word[3]);

		if (strcmp(word[0], "IFNDEF") == 0 && n == 2) {
			/* Only BOOST_USE_TSX is tested, and it is never defined in PHP's build. */
			if (strcmp(word[1], "BOOST_USE_TSX") != 0) die("%s:%d: unknown symbol %s", argv[1], lineno, word[1]);
			depth++;
		} else if (strcmp(word[0], "ENDIF") == 0 && n == 1) {
			if (depth-- == 0) die("%s:%d: ENDIF without IFNDEF", argv[1], lineno);
		} else if (strcmp(word[0], "EXTERN") == 0 && n == 2) {
			char *colon = strchr(word[1], ':');
			if (!colon || strcmp(colon, ":PROC") != 0) die("%s:%d: unsupported EXTERN", argv[1], lineno);
			*colon = 0;
			fprintf(out, ".extern %s\n", word[1]);
		} else if (strcmp(word[0], ".code") == 0 && n == 1) {
			fputs(".text\n.p2align 4\n", out);
		} else if (n >= 2 && strcmp(word[1], "PROC") == 0) {
			/* "NAME PROC BOOST_CONTEXT_EXPORT FRAME": a public function with
			 * unwind data. BOOST_CONTEXT_EXPORT is empty in a static build. */
			if (n != 4 || strcmp(word[2], "BOOST_CONTEXT_EXPORT") != 0 || strcmp(word[3], "FRAME") != 0)
				die("%s:%d: unsupported PROC form", argv[1], lineno);
			fprintf(out, ".globl %s\n.def %s; .scl 2; .type 32; .endef\n.seh_proc %s\n%s:\n",
				word[0], word[0], word[0], word[0]);
		} else if (strcmp(word[0], ".endprolog") == 0 && n == 1) {
			fputs(".seh_endprologue\n", out);
		} else if (n == 2 && strcmp(word[1], "ENDP") == 0) {
			fputs(".seh_endproc\n", out);
		} else if (strcmp(word[0], "END") == 0 && n == 1) {
			ended = 1;
		} else if (isupper((unsigned char)word[0][0]) || word[0][0] == '.') {
			die("%s:%d: unsupported directive: %s", argv[1], lineno, s);
		} else if (strcmp(word[0], "lea") == 0 && n == 3 && is_identifier(word[2]) && !is_register(word[2])) {
			/* "lea reg, label": the Microsoft assembler makes this
			 * RIP-relative; clang needs it spelled out. */
			fprintf(out, "    lea %s [rip+%s]\n", word[1], word[2]);
		} else {
			put_instruction(out, s);
		}
	}
	if (depth != 0) die("%s: IFNDEF without ENDIF", argv[1]);
	if (!ended) die("%s: no END", argv[1]);
	fclose(in);
	if (fclose(out) != 0) die("cannot write %s", argv[2]);
	return 0;
}
